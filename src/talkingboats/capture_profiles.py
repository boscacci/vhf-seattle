import argparse
import json
from dataclasses import dataclass

from talkingboats.channel_metadata import CHANNEL_METADATA, VOICE_NET_BALANCED_CHANNELS


@dataclass(frozen=True)
class CaptureChannel:
    channel: str
    label: str
    frequency_hz: int
    slot_seconds: int | None = None


@dataclass(frozen=True)
class CaptureProfile:
    name: str
    mode: str
    channels: tuple[CaptureChannel, ...]
    center_frequency_hz: int | None = None
    sample_rate_hz: int | None = None


@dataclass(frozen=True)
class AirbandIcecastOutput:
    channel: str
    server: str
    port: int
    mountpoint: str
    name: str
    password: str
    username: str = "source"
    genre: str = "Marine VHF"
    continuous: bool = True


